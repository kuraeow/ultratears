#!/usr/bin/env python3
"""Compiles the port's SMAA 1x passes (src/gfx/shaders/smaa.comp, around third_party/smaa/SMAA.hlsl, MIT) into SPIR-V
and writes src/gfx/vkb_smaa_spv.h: one array of words per pass (0 edges, 1 blending weights, 2 neighbourhood blending).
src/gfx/vkb_smaa.c runs them.

Development tool only: the header is checked in, so building UltraTears needs no glslang.
Needs glslangValidator on PATH or in C:/msys64/clang64/bin (or GLSLANG set).
"""
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def glslang():
    p = os.environ.get('GLSLANG') or shutil.which('glslangValidator')
    if not p and os.path.exists('C:/msys64/clang64/bin/glslangValidator.exe'):
        p = 'C:/msys64/clang64/bin/glslangValidator.exe'
    if not p:
        sys.exit('glslangValidator not found (set GLSLANG)')
    return p


def main():
    src = os.path.join(ROOT, 'src', 'gfx', 'shaders', 'smaa.comp')
    lines = ['// Generated by tools/build_smaa.py from src/gfx/shaders/smaa.comp (SMAA: third_party/smaa, MIT). Do not edit.',
             '#pragma once', '#include <stdint.h>']
    for p, name in enumerate(('smaa_edges', 'smaa_weights', 'smaa_blend')):
        with tempfile.TemporaryDirectory() as tmp:
            spv = os.path.join(tmp, name + '.spv')
            r = subprocess.run([glslang(), '-V', '--target-env', 'vulkan1.2', '-DPASS=%d' % p, '-o', spv, src],
                               capture_output=True, text=True)
            if r.returncode:
                sys.exit(r.stdout + r.stderr)
            words = open(spv, 'rb').read()
        n = len(words) // 4
        lines.append('static const uint32_t %s_spv[%d] = {' % (name, n))
        for i in range(0, n, 8):
            lines.append('    ' + ', '.join('0x%08x' % int.from_bytes(words[j * 4:j * 4 + 4], 'little')
                                           for j in range(i, min(i + 8, n))) + ',')
        lines.append('};')
        print('%s %d words' % (name, n))
    with open(os.path.join(ROOT, 'src', 'gfx', 'vkb_smaa_spv.h'), 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
