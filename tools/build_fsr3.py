#!/usr/bin/env python3
"""Compiles AMD FidelityFX FSR 3.1's upscaler passes (third_party/fsr3, MIT, from the FidelityFX SDK v1.1.4) into
SPIR-V and writes third_party/fsr3/fsr3_spv.h: one array of words per pass and variant, with the pass's descriptor
bindings (binding number, kind, resource name) read back from the SPIR-V. src/gfx/vkb_fsr3.c runs them.

Development tool only: the header is checked in, so building UltraTears needs neither glslang nor SPIRV-Cross.
Needs glslangValidator and spirv-cross on PATH or in C:/msys64/clang64/bin (or GLSLANG / SPIRV_CROSS set).

One permutation is built, the one the port uses: tonemapped (not HDR) colour, since the game's last scaling pass reads
its picture after the tonemap and its FXAA; motion vectors at the render size and without jitter; depth as TotK draws it
(LEQUAL, range 0..1: not inverted); the Lanczos weights computed (not the LUT). Twice: 32-bit maths, and the SDK's 16-bit
permutation (FFX_HALF, all passes but RCAS) for GPUs that do half maths fast (the Steam Deck). The accumulate pass comes twice, with and without
the sharpening that hands its result to RCAS.

Also compiles the port's own camera motion pass (src/gfx/shaders/tsr_mv.comp, GPL-3.0-or-later) into
src/gfx/vkb_tsr_mv_spv.h.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FSR = os.path.join(ROOT, 'third_party', 'fsr3')


def tool(env, name):
    p = os.environ.get(env) or shutil.which(name)
    if not p:
        for d in ('C:/msys64/clang64/bin',):
            c = os.path.join(d, name + '.exe')
            if os.path.exists(c):
                p = c
    if not p:
        sys.exit('%s not found (set %s)' % (name, env))
    return p


BASE = {
    'FFX_GPU': 1, 'FFX_GLSL': 1, 'FFX_HALF': 0,
    'FFX_FSR3UPSCALER_OPTION_UPSAMPLE_SAMPLERS_USE_DATA_HALF': 0,
    'FFX_FSR3UPSCALER_OPTION_ACCUMULATE_SAMPLERS_USE_DATA_HALF': 0,
    'FFX_FSR3UPSCALER_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF': 0,
    'FFX_FSR3UPSCALER_OPTION_POSTPROCESSLOCKSTATUS_SAMPLERS_USE_DATA_HALF': 0,
    'FFX_FSR3UPSCALER_OPTION_UPSAMPLE_USE_LANCZOS_TYPE': 2,
    'FFX_FSR3UPSCALER_OPTION_REPROJECT_USE_LANCZOS_TYPE': 0,
    'FFX_FSR3UPSCALER_OPTION_HDR_COLOR_INPUT': 0,
    'FFX_FSR3UPSCALER_OPTION_LOW_RESOLUTION_MOTION_VECTORS': 1,
    'FFX_FSR3UPSCALER_OPTION_JITTERED_MOTION_VECTORS': 0,
    'FFX_FSR3UPSCALER_OPTION_INVERTED_DEPTH': 0,
    'FFX_FSR3UPSCALER_OPTION_APPLY_SHARPENING': 0,
}

# (C name, pass file, extra defines) in dispatch order
PASSES = [
    ('prepare_inputs', 'prepare_inputs', {}),
    ('luma_pyramid', 'luma_pyramid', {}),
    ('shading_change_pyramid', 'shading_change_pyramid', {}),
    ('shading_change', 'shading_change', {}),
    ('prepare_reactivity', 'prepare_reactivity', {}),
    ('luma_instability', 'luma_instability', {}),
    ('accumulate', 'accumulate', {}),
    ('accumulate_sharpen', 'accumulate', {'FFX_FSR3UPSCALER_OPTION_APPLY_SHARPENING': 1}),
    ('rcas', 'rcas', {}),
]

KIND = {'separate_images': 'FSR3_SRV', 'images': 'FSR3_UAV', 'ubos': 'FSR3_CB', 'separate_samplers': 'FSR3_SAMPLER'}


def main():
    glslang, cross = tool('GLSLANG', 'glslangValidator'), tool('SPIRV_CROSS', 'spirv-cross')
    out = ['// Generated by tools/build_fsr3.py from third_party/fsr3 (AMD FidelityFX SDK v1.1.4, MIT; see LICENSE.txt).',
           '// Do not edit. One permutation: tonemapped colour, render-size unjittered motion vectors, depth not inverted; fp32 and fp16.',
           '#pragma once', '#include <stdint.h>', '',
           'enum { FSR3_SRV, FSR3_UAV, FSR3_CB, FSR3_SAMPLER };',
           'typedef struct { uint32_t binding; int kind; const char *name; } fsr3_binding;',
           'typedef struct { const char *name; const uint32_t *code; uint32_t size; const fsr3_binding *b; uint32_t nb;'
           ' uint32_t lx, ly; } fsr3_pass_code;', '']
    tables = {'': [], '_h': []}
    with tempfile.TemporaryDirectory() as tmp:
      for suffix, half in (('', 0), ('_h', 1)):
        table = tables[suffix]
        for pname, src, extra in PASSES:
            if half and pname == 'rcas':   # as the SDK: RCAS stays 32-bit
                table.append(tables[''][-1])
                continue
            cname = pname + suffix
            d = dict(BASE, **extra)
            if half:   # the SDK's 16-bit permutation: half maths, the reprojection's samples in half too
                d['FFX_HALF'] = 1
                d['FFX_FSR3UPSCALER_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF'] = 1
            spv = os.path.join(tmp, cname + '.spv')
            cmd = [glslang, '-V', '--target-env', 'vulkan1.2', '-S', 'comp', '-I' + os.path.join(FSR, 'gpu'), '-o', spv]
            cmd += ['-D%s=%s' % kv for kv in sorted(d.items())]
            cmd.append(os.path.join(FSR, 'passes', 'ffx_fsr3upscaler_%s_pass.glsl' % src))
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode:
                sys.exit(r.stdout + r.stderr)
            refl = json.loads(subprocess.run([cross, spv, '--reflect'], capture_output=True, text=True, check=True).stdout)
            binds = []
            for key, kind in KIND.items():
                for res in refl.get(key, []):
                    if res.get('set', 0) != 0:
                        sys.exit('%s: %s in set %d' % (cname, res['name'], res['set']))
                    name = res['name']
                    if key == 'ubos':   # the block's type name: cbFSR3UPSCALER_t -> cbFSR3UPSCALER
                        name = refl['types'][res['type']]['name'].removesuffix('_t')
                    binds.append((res['binding'], kind, name))
            binds.sort()
            ep = refl['entryPoints'][0]
            lx, ly = ep['workgroup_size'][0], ep['workgroup_size'][1]
            words = open(spv, 'rb').read()
            n = len(words) // 4
            out.append('static const uint32_t fsr3_%s_spv[%d] = {' % (cname, n))
            for i in range(0, n, 8):
                chunk = [int.from_bytes(words[j * 4:j * 4 + 4], 'little') for j in range(i, min(i + 8, n))]
                out.append('    ' + ', '.join('0x%08x' % w for w in chunk) + ',')
            out.append('};')
            out.append('static const fsr3_binding fsr3_%s_b[] = {' % cname)
            for b, kind, name in binds:
                out.append('    {%d, %s, "%s"},' % (b, kind, name))
            out.append('};')
            table.append('    {"%s", fsr3_%s_spv, sizeof fsr3_%s_spv, fsr3_%s_b, sizeof fsr3_%s_b / sizeof fsr3_%s_b[0], %d, %d},'
                         % (pname, cname, cname, cname, cname, cname, lx, ly))
            print('%-24s %6d words, %2d bindings, group %dx%d' % (cname, n, len(binds), lx, ly))
    out.append('enum { %s, FSR3_NPASS };' % ', '.join('FSR3_P_' + p[0].upper() for p in PASSES))
    out.append('static const fsr3_pass_code fsr3_passes[FSR3_NPASS] = {')
    out += tables['']
    out.append('};')
    out.append('// 16-bit maths (FFX_HALF): GPUs with shaderFloat16 and shaderInt16 (the Steam Deck); RCAS is the 32-bit one')
    out.append('static const fsr3_pass_code fsr3_passes_h[FSR3_NPASS] = {')
    out += tables['_h']
    out.append('};')
    with open(os.path.join(FSR, 'fsr3_spv.h'), 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    # the port's own shaders: the camera motion pass and the per-object motion fragment shader
    lines = ['// Generated by tools/build_fsr3.py from src/gfx/shaders/tsr_mv.comp and tsr_obj.frag. Do not edit.',
             '#pragma once', '#include <stdint.h>']
    for name, file in (('tsr_mv', 'tsr_mv.comp'), ('tsr_obj', 'tsr_obj.frag')):
        src = os.path.join(ROOT, 'src', 'gfx', 'shaders', file)
        with tempfile.TemporaryDirectory() as tmp:
            spv = os.path.join(tmp, name + '.spv')
            r = subprocess.run([glslang, '-V', '--target-env', 'vulkan1.2', '-o', spv, src], capture_output=True, text=True)
            if r.returncode:
                sys.exit(r.stdout + r.stderr)
            words = open(spv, 'rb').read()
        n = len(words) // 4
        lines.append('static const uint32_t %s_spv[%d] = {' % (name, n))
        for i in range(0, n, 8):
            lines.append('    ' + ', '.join('0x%08x' % int.from_bytes(words[j * 4:j * 4 + 4], 'little')
                                           for j in range(i, min(i + 8, n))) + ',')
        lines.append('};')
        print('%s %d words' % (name, n))
    with open(os.path.join(ROOT, 'src', 'gfx', 'vkb_tsr_mv_spv.h'), 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
